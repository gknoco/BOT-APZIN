CREATE TABLE IF NOT EXISTS public.royal_match_outbox (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partida_id text NOT NULL REFERENCES public.royal_partidas(id) ON DELETE RESTRICT,
  tipo text NOT NULL CHECK (tipo IN ('cartao', 'log', 'economia_legada')),
  payload jsonb NOT NULL,
  estado text NOT NULL DEFAULT 'pendente' CHECK (estado IN ('pendente', 'processando', 'concluido', 'revisao')),
  tentativas integer NOT NULL DEFAULT 0,
  disponivel_em timestamptz NOT NULL DEFAULT clock_timestamp(),
  lease_ate timestamptz,
  lease_token uuid,
  ultimo_erro text,
  criado_em timestamptz NOT NULL DEFAULT clock_timestamp(),
  concluido_em timestamptz,
  UNIQUE (partida_id, tipo)
);
CREATE INDEX IF NOT EXISTS royal_match_outbox_pendencias_idx
  ON public.royal_match_outbox (disponivel_em, id) WHERE estado <> 'concluido';
ALTER TABLE public.royal_match_outbox ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.royal_match_outbox FROM PUBLIC, anon, authenticated, service_role;
GRANT SELECT ON TABLE public.royal_match_outbox TO service_role;
REVOKE ALL ON SEQUENCE public.royal_match_outbox_id_seq FROM PUBLIC, anon, authenticated, service_role;

-- Recupera finalizações anteriores que nunca chegaram à RPC econômica. Congela
-- o que é possível reconstruir. A ausência da chave não prova que o prêmio
-- nunca foi importado ou pago manualmente: exige revisão antes de liberar.
-- Não reconta resultados cuja chave econômica já existe.
INSERT INTO public.royal_match_outbox(partida_id, tipo, estado, payload)
SELECT p.id, 'economia_legada', 'revisao', jsonb_build_object(
  'guild_id', p.guild_id, 'winner_time', p.vencedor_time,
  'stake', greatest(0, p.preco), 'reason', coalesce(nullif(p.motivo_fim, ''), 'resultado'),
  'players', coalesce((SELECT jsonb_agg(jsonb_build_object('user_id', j.user_id,
    'team', j.time, 'confirmed', j.confirmou = 1) ORDER BY j.time, j.ordem, j.user_id)
    FROM public.royal_partida_jogadores j WHERE j.partida_id = p.id), '[]'::jsonb))
FROM public.royal_partidas p
WHERE p.status = 'finalizada' AND NOT EXISTS (
  SELECT 1 FROM public.royal_match_stats_applied s
  WHERE s.guild_id = trim(p.guild_id) AND s.match_id = trim(p.id))
ON CONFLICT (partida_id, tipo) DO NOTHING;

CREATE OR REPLACE FUNCTION public.royal_operacional_encerrar_partida(
  p_id text, p_vencedor_time integer, p_autor_id text DEFAULT NULL,
  p_motivo text DEFAULT 'resultado', p_cancelar boolean DEFAULT false
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE
  v_partida public.royal_partidas%ROWTYPE;
  v_jogadores jsonb; v_players jsonb; v_acao text; v_detalhe text;
  v_motivo text := coalesce(nullif(p_motivo, ''), CASE WHEN p_cancelar THEN 'cancelada pela staff' ELSE 'resultado' END);
  v_replay boolean := false;
BEGIN
  IF p_cancelar IS NULL THEN RAISE EXCEPTION 'Tipo de encerramento inválido'; END IF;
  IF NOT p_cancelar AND (p_vencedor_time IS NULL OR p_vencedor_time NOT IN (1, 2)) THEN
    RAISE EXCEPTION 'O time vencedor precisa ser 1 ou 2.';
  END IF;
  IF p_cancelar THEN v_motivo := left(v_motivo, 200); END IF;
  SELECT * INTO v_partida FROM public.royal_partidas WHERE id = p_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Partida não encontrada.'; END IF;
  IF v_partida.status IN ('finalizada', 'cancelada') THEN
    IF (p_cancelar AND v_partida.status = 'cancelada' AND v_partida.motivo_fim IS NOT DISTINCT FROM v_motivo)
       OR (NOT p_cancelar AND v_partida.status = 'finalizada'
           AND v_partida.vencedor_time IS NOT DISTINCT FROM p_vencedor_time
           AND coalesce(nullif(v_partida.motivo_fim, ''), 'resultado') = v_motivo) THEN
      v_replay := true;
    ELSE
      RAISE EXCEPTION 'Essa partida já foi encerrada com outro resultado.';
    END IF;
  END IF;
  SELECT coalesce(jsonb_agg(to_jsonb(j) - 'ordem' ORDER BY j.time, j.ordem, j.user_id), '[]'::jsonb),
         coalesce(jsonb_agg(jsonb_build_object('user_id', j.user_id, 'team', j.time,
           'confirmed', j.confirmou = 1) ORDER BY j.time, j.ordem, j.user_id), '[]'::jsonb)
    INTO v_jogadores, v_players FROM public.royal_partida_jogadores j WHERE j.partida_id = p_id;
  IF NOT p_cancelar THEN
    IF v_replay AND NOT EXISTS (SELECT 1 FROM public.royal_match_stats_applied
      WHERE guild_id = trim(v_partida.guild_id) AND match_id = trim(p_id))
      THEN
      RAISE EXCEPTION 'Resultado legado pendente de revisão econômica ou processamento antes de qualquer crédito.';
    END IF;
    -- A RPC econômica possui sua própria chave (guild_id, match_id), locks e
    -- validação de replay; falhas revertem também o encerramento e a outbox.
    PERFORM public.royal_apply_match_result(v_partida.guild_id, p_id, p_vencedor_time,
      greatest(0, v_partida.preco)::bigint, v_motivo, v_players);
  END IF;
  IF v_replay THEN
    RETURN jsonb_build_object('partida', to_jsonb(v_partida), 'jogadores', v_jogadores, 'replay', true);
  END IF;
  UPDATE public.royal_partidas SET status = CASE WHEN p_cancelar THEN 'cancelada' ELSE 'finalizada' END,
    vencedor_time = CASE WHEN p_cancelar THEN NULL ELSE p_vencedor_time END,
    motivo_fim = v_motivo, finalizada_em = public.royal_operacional_agora()
    WHERE id = p_id RETURNING * INTO v_partida;
  v_acao := CASE WHEN p_cancelar THEN 'Partida cancelada' WHEN v_motivo = 'wo' THEN 'WO aplicado' ELSE 'Resultado registrado' END;
  v_detalhe := CASE WHEN p_cancelar THEN p_id || ' · ' || v_motivo
    ELSE 'Partida ' || p_id || ' · time ' || p_vencedor_time || ' venceu · ' || v_partida.modo || ' ' || v_partida.preco END;
  INSERT INTO public.royal_audit_events(guild_id, actor_id, action, entity_type, entity_id, detail, after_data)
    VALUES(v_partida.guild_id, p_autor_id, v_acao, 'partida', p_id, v_detalhe, to_jsonb(v_partida));
  INSERT INTO public.royal_match_outbox(partida_id, tipo, payload) VALUES
    (p_id, 'cartao', jsonb_build_object('partida_id', p_id)),
    (p_id, 'log', jsonb_build_object('guild_id', v_partida.guild_id, 'autor_id', p_autor_id,
      'acao', v_acao, 'detalhe', v_detalhe));
  RETURN jsonb_build_object('partida', to_jsonb(v_partida), 'jogadores', v_jogadores, 'replay', false);
END $$;

-- Uma única reivindicação por transação. Token muda a cada lease: trabalhador
-- antigo não pode concluir/reagendar o evento depois que outro o reivindicar.
CREATE OR REPLACE FUNCTION public.royal_match_outbox_reivindicar(p_token uuid)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE v_evento public.royal_match_outbox%ROWTYPE;
BEGIN
  IF p_token IS NULL THEN RAISE EXCEPTION 'Token obrigatório'; END IF;
  SELECT * INTO v_evento FROM public.royal_match_outbox
   WHERE (estado = 'pendente' AND disponivel_em <= clock_timestamp())
      OR (estado = 'processando' AND lease_ate <= clock_timestamp())
   ORDER BY disponivel_em, id LIMIT 1 FOR UPDATE SKIP LOCKED;
  IF NOT FOUND THEN RETURN NULL; END IF;
  UPDATE public.royal_match_outbox SET estado = 'processando', lease_token = p_token,
    lease_ate = clock_timestamp() + interval '2 minutes', tentativas = tentativas + 1
   WHERE id = v_evento.id RETURNING * INTO v_evento;
  RETURN to_jsonb(v_evento) || jsonb_build_object('id', v_evento.id::text);
END $$;

CREATE OR REPLACE FUNCTION public.royal_match_outbox_concluir(p_id bigint, p_token uuid, p_sucesso boolean, p_erro text DEFAULT NULL)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE v_count integer;
BEGIN
  IF p_sucesso IS NULL THEN RAISE EXCEPTION 'Resultado obrigatório'; END IF;
  -- Economia legada só pode ser concluída na RPC transacional própria.
  UPDATE public.royal_match_outbox SET
    estado = CASE WHEN p_sucesso THEN 'concluido' ELSE 'pendente' END,
    concluido_em = CASE WHEN p_sucesso THEN clock_timestamp() ELSE NULL END,
    disponivel_em = CASE WHEN p_sucesso THEN disponivel_em ELSE clock_timestamp() +
      make_interval(secs => least(300, (5 * power(2, least(tentativas - 1, 6)))::integer)) END,
    ultimo_erro = CASE WHEN p_sucesso THEN NULL ELSE left(coalesce(p_erro, 'erro'), 500) END,
    lease_token = NULL, lease_ate = NULL
  WHERE id = p_id AND estado = 'processando' AND lease_token = p_token
    AND (NOT p_sucesso OR tipo <> 'economia_legada');
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count = 1;
END $$;

CREATE OR REPLACE FUNCTION public.royal_match_outbox_economia_legada(p_id bigint, p_token uuid)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE v_evento public.royal_match_outbox%ROWTYPE; v_p jsonb;
BEGIN
  SELECT * INTO v_evento FROM public.royal_match_outbox
    WHERE id = p_id AND estado = 'processando' AND lease_token = p_token AND tipo = 'economia_legada' FOR UPDATE;
  IF NOT FOUND THEN RETURN false; END IF;
  v_p := v_evento.payload;
  PERFORM public.royal_apply_match_result(v_p->>'guild_id', v_evento.partida_id,
    (v_p->>'winner_time')::integer, (v_p->>'stake')::bigint, v_p->>'reason', v_p->'players');
  UPDATE public.royal_match_outbox SET estado = 'concluido', concluido_em = clock_timestamp(),
    lease_token = NULL, lease_ate = NULL, ultimo_erro = NULL WHERE id = p_id;
  RETURN true;
END $$;

REVOKE ALL ON FUNCTION public.royal_operacional_encerrar_partida(text,integer,text,text,boolean) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.royal_match_outbox_reivindicar(uuid) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.royal_match_outbox_concluir(bigint,uuid,boolean,text) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.royal_match_outbox_economia_legada(bigint,uuid) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.royal_operacional_encerrar_partida(text,integer,text,text,boolean),
  public.royal_match_outbox_reivindicar(uuid), public.royal_match_outbox_concluir(bigint,uuid,boolean,text),
  public.royal_match_outbox_economia_legada(bigint,uuid) TO service_role;
COMMIT;
