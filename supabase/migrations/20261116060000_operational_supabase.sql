CREATE OR REPLACE FUNCTION public.royal_operacional_agora() RETURNS bigint
LANGUAGE sql VOLATILE SET search_path=public,pg_temp AS $$
  SELECT floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint
$$;

CREATE OR REPLACE FUNCTION public.royal_operacional_entrar_fila(
  p_guild_id text,p_modo text,p_preco integer,p_gelo text,p_user_id text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_inseridos integer; v_posicao bigint;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended(jsonb_build_array('royal-fila',p_guild_id,p_modo,p_preco,p_gelo)::text,0));
  INSERT INTO royal_filas(guild_id,modo,preco,gelo,user_id,entrou_em)
  VALUES(p_guild_id,p_modo,p_preco,p_gelo,p_user_id,royal_operacional_agora()) ON CONFLICT DO NOTHING;
  GET DIAGNOSTICS v_inseridos = ROW_COUNT;
  SELECT q.posicao INTO v_posicao FROM (
    SELECT user_id,row_number() OVER (ORDER BY entrou_em,id) AS posicao FROM royal_filas
    WHERE guild_id=p_guild_id AND modo=p_modo AND preco=p_preco AND gelo=p_gelo
  ) q WHERE q.user_id=p_user_id;
  RETURN jsonb_build_object('entrou',v_inseridos=1,'posicao',v_posicao);
END $$;

CREATE OR REPLACE FUNCTION public.royal_operacional_reservar_fila(
  p_guild_id text,p_modo text,p_preco integer,p_gelo text,p_quantidade integer
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_ids bigint[]; v_jogadores jsonb;
BEGIN
  IF p_quantidade IS NULL OR p_quantidade<1 THEN RAISE EXCEPTION 'A quantidade de jogadores precisa ser um inteiro positivo.'; END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended(jsonb_build_array('royal-fila',p_guild_id,p_modo,p_preco,p_gelo)::text,0));
  SELECT array_agg(q.id ORDER BY q.entrou_em,q.id),jsonb_agg(q.user_id ORDER BY q.entrou_em,q.id)
  INTO v_ids,v_jogadores FROM (
    SELECT id,user_id,entrou_em FROM royal_filas
    WHERE guild_id=p_guild_id AND modo=p_modo AND preco=p_preco AND gelo=p_gelo
    ORDER BY entrou_em,id LIMIT p_quantidade FOR UPDATE
  ) q;
  IF coalesce(array_length(v_ids,1),0)<p_quantidade THEN RETURN NULL; END IF;
  DELETE FROM royal_filas WHERE id=ANY(v_ids);
  RETURN v_jogadores;
END $$;

CREATE OR REPLACE FUNCTION public.royal_operacional_modos_fila(p_guild_id text)
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$
  SELECT coalesce(jsonb_agg(to_jsonb(q) ORDER BY q.modo),'[]'::jsonb)
  FROM (SELECT modo,count(*) AS total FROM royal_filas WHERE guild_id=p_guild_id GROUP BY modo) q
$$;

CREATE OR REPLACE FUNCTION public.royal_operacional_criar_partida(
  p_id text,p_guild_id text,p_modo text,p_preco integer,p_gelo text,p_canal_id text,p_jogadores jsonb
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_partida royal_partidas%rowtype;
BEGIN
  IF jsonb_typeof(p_jogadores) IS DISTINCT FROM 'array' OR jsonb_array_length(p_jogadores)=0 THEN
    RAISE EXCEPTION 'Não dá para criar partida sem jogadores.';
  END IF;
  IF EXISTS(SELECT 1 FROM jsonb_array_elements(p_jogadores) j
    WHERE nullif(j->>'user_id','') IS NULL OR (j->>'time')::integer NOT IN (1,2) OR j->>'time' IS NULL) THEN
    RAISE EXCEPTION 'Cada jogador precisa ter usuário e time 1 ou 2.';
  END IF;
  INSERT INTO royal_partidas(id,guild_id,modo,preco,gelo,canal_id,status,criado_em)
  VALUES(p_id,p_guild_id,p_modo,p_preco,p_gelo,p_canal_id,'confirmando',royal_operacional_agora()) RETURNING * INTO v_partida;
  INSERT INTO royal_partida_jogadores(partida_id,user_id,time,confirmou,ordem)
  SELECT p_id,j.valor->>'user_id',(j.valor->>'time')::integer,0,j.ordem::integer
  FROM jsonb_array_elements(p_jogadores) WITH ORDINALITY j(valor,ordem);
  RETURN to_jsonb(v_partida);
END $$;

CREATE OR REPLACE FUNCTION public.royal_operacional_confirmar_partida(p_id text,p_user_id text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_partida royal_partidas%rowtype; v_eu royal_partida_jogadores%rowtype;
  v_total bigint; v_confirmados bigint; v_ja boolean;
BEGIN
  SELECT * INTO v_partida FROM royal_partidas WHERE id=p_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Partida não encontrada.'; END IF;
  SELECT count(*),count(*) FILTER (WHERE confirmou=1) INTO v_total,v_confirmados FROM royal_partida_jogadores WHERE partida_id=p_id;
  IF v_partida.status<>'confirmando' THEN
    RETURN jsonb_build_object('ok',false,'motivo','status','partida',to_jsonb(v_partida),'confirmados',v_confirmados,'total',v_total);
  END IF;
  SELECT * INTO v_eu FROM royal_partida_jogadores WHERE partida_id=p_id AND user_id=p_user_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Você não está nessa partida.'; END IF;
  v_ja := v_eu.confirmou=1;
  IF NOT v_ja THEN
    UPDATE royal_partida_jogadores SET confirmou=1 WHERE partida_id=p_id AND user_id=p_user_id;
    v_confirmados := v_confirmados+1;
  END IF;
  IF v_confirmados>=v_total THEN
    UPDATE royal_partidas SET status='aguardando_mediador' WHERE id=p_id RETURNING * INTO v_partida;
  END IF;
  RETURN jsonb_build_object('ok',true,'jaConfirmou',v_ja,'confirmados',v_confirmados,'total',v_total,
    'completo',v_confirmados>=v_total,'partida',to_jsonb(v_partida));
END $$;

CREATE OR REPLACE FUNCTION public.royal_operacional_alterar_partida(p_id text,p_acao text,p_dados jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_partida royal_partidas%rowtype;
BEGIN
  SELECT * INTO v_partida FROM royal_partidas WHERE id=p_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Partida não encontrada.'; END IF;
  CASE p_acao
  WHEN 'regras' THEN
    IF v_partida.status IN ('finalizada','cancelada') THEN RAISE EXCEPTION 'Essa partida já foi encerrada.'; END IF;
    IF length(trim(coalesce(p_dados->>'regras','')))<5 THEN RAISE EXCEPTION 'Escreva a regra da partida (pelo menos 5 letras).'; END IF;
    UPDATE royal_partidas SET regras=left(trim(p_dados->>'regras'),900),regras_por=p_dados->>'autor_id' WHERE id=p_id;
  WHEN 'assumir' THEN
    IF v_partida.mediador_id IS NOT NULL AND v_partida.mediador_id IS DISTINCT FROM p_dados->>'mediador_id' THEN
      RAISE EXCEPTION 'Essa sala já tem um mediador responsável.';
    END IF;
    UPDATE royal_partidas SET mediador_id=p_dados->>'mediador_id',comissao=coalesce((p_dados->>'comissao')::double precision,0),status='aguardando_pagamento'
    WHERE id=p_id AND status IN ('confirmando','aguardando_mediador','aguardando_pagamento');
  WHEN 'pago' THEN
    IF v_partida.status NOT IN ('aguardando_pagamento','pago') THEN RAISE EXCEPTION 'Só dá para confirmar pagamento com o mediador já na sala.'; END IF;
    UPDATE royal_partidas SET status='pago',pago_em=royal_operacional_agora() WHERE id=p_id;
  WHEN 'sala' THEN
    IF v_partida.status NOT IN ('pago','sala_liberada') THEN RAISE EXCEPTION 'Confirme o pagamento antes de liberar a criação da sala.'; END IF;
    IF nullif(trim(p_dados->>'sala_id'),'') IS NULL THEN RAISE EXCEPTION 'Informe o ID da sala.'; END IF;
    UPDATE royal_partidas SET sala_id=left(trim(p_dados->>'sala_id'),40),sala_senha=left(trim(p_dados->>'sala_senha'),40),
      nix_sessao=coalesce(nullif(left(trim(p_dados->>'nix_sessao'),64),''),nix_sessao),
      status='sala_liberada',liberada_em=royal_operacional_agora() WHERE id=p_id;
  ELSE RAISE EXCEPTION 'Transição operacional inválida: %',p_acao;
  END CASE;
  SELECT * INTO v_partida FROM royal_partidas WHERE id=p_id;
  RETURN to_jsonb(v_partida);
END $$;

CREATE OR REPLACE FUNCTION public.royal_operacional_dar_go(p_id text,p_user_id text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_partida royal_partidas%rowtype; v_total bigint; v_deram bigint; v_inseridos integer; v_iniciou boolean:=false;
BEGIN
  SELECT * INTO v_partida FROM royal_partidas WHERE id=p_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Partida não encontrada.'; END IF;
  IF v_partida.status IN ('finalizada','cancelada') THEN RAISE EXCEPTION 'Essa partida já foi encerrada.'; END IF;
  IF v_partida.status NOT IN ('sala_liberada','em_andamento') THEN
    RAISE EXCEPTION 'A sala do jogo ainda não foi liberada. O `/go` só vale depois que o mediador publicar o ID e a senha.';
  END IF;
  IF NOT EXISTS(SELECT 1 FROM royal_partida_jogadores WHERE partida_id=p_id AND user_id=p_user_id) THEN RAISE EXCEPTION 'Você não está nessa partida.'; END IF;
  INSERT INTO royal_partida_go(partida_id,user_id,criado_em) VALUES(p_id,p_user_id,royal_operacional_agora()) ON CONFLICT DO NOTHING;
  GET DIAGNOSTICS v_inseridos=ROW_COUNT;
  SELECT count(*) INTO v_total FROM royal_partida_jogadores WHERE partida_id=p_id;
  SELECT count(*) INTO v_deram FROM royal_partida_go WHERE partida_id=p_id;
  IF v_deram>=v_total AND v_partida.status='sala_liberada' THEN
    UPDATE royal_partidas SET status='em_andamento' WHERE id=p_id RETURNING * INTO v_partida;
    v_iniciou:=true;
  END IF;
  RETURN jsonb_build_object('jaDeu',v_inseridos=0,'deram',least(v_deram,v_total),'total',v_total,'iniciou',v_iniciou,'partida',to_jsonb(v_partida));
END $$;

CREATE OR REPLACE FUNCTION public.royal_operacional_encerrar_partida(
  p_id text,p_vencedor_time integer,p_autor_id text DEFAULT NULL,p_motivo text DEFAULT 'resultado',p_cancelar boolean DEFAULT false
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_partida royal_partidas%rowtype; v_jogadores jsonb; v_acao text; v_detalhe text;
BEGIN
  SELECT * INTO v_partida FROM royal_partidas WHERE id=p_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Partida não encontrada.'; END IF;
  IF v_partida.status IN ('finalizada','cancelada') THEN RAISE EXCEPTION 'Essa partida já foi encerrada.'; END IF;
  IF NOT p_cancelar AND (p_vencedor_time IS NULL OR p_vencedor_time NOT IN (1,2)) THEN RAISE EXCEPTION 'O time vencedor precisa ser 1 ou 2.'; END IF;
  SELECT coalesce(jsonb_agg(to_jsonb(j)-'ordem' ORDER BY j.time,j.ordem,j.user_id),'[]'::jsonb)
    INTO v_jogadores FROM royal_partida_jogadores j WHERE partida_id=p_id;
  UPDATE royal_partidas SET status=CASE WHEN p_cancelar THEN 'cancelada' ELSE 'finalizada' END,
    vencedor_time=CASE WHEN p_cancelar THEN vencedor_time ELSE p_vencedor_time END,
    motivo_fim=CASE WHEN p_cancelar THEN left(p_motivo,200) ELSE p_motivo END,
    finalizada_em=royal_operacional_agora() WHERE id=p_id RETURNING * INTO v_partida;
  v_acao:=CASE WHEN p_cancelar THEN 'Partida cancelada' WHEN p_motivo='wo' THEN 'WO aplicado' ELSE 'Resultado registrado' END;
  v_detalhe:=CASE WHEN p_cancelar THEN p_id||' · '||p_motivo
    ELSE 'Partida '||p_id||' · time '||p_vencedor_time||' venceu · '||v_partida.modo||' '||v_partida.preco END;
  INSERT INTO royal_audit_events(guild_id,actor_id,action,entity_type,entity_id,detail,after_data)
    VALUES(v_partida.guild_id,p_autor_id,v_acao,'partida',p_id,v_detalhe,to_jsonb(v_partida));
  -- Estatísticas econômicas continuam pela RPC idempotente royal_apply_match_result,
  -- chamada pelo consumidor; não há aplicação duplicada neste estado operacional.
  RETURN jsonb_build_object('partida',to_jsonb(v_partida),'jogadores',v_jogadores);
END $$;

CREATE OR REPLACE FUNCTION public.royal_operacional_receita(p_guild_id text,p_desde_ms bigint DEFAULT 0)
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$
  SELECT coalesce(jsonb_agg(to_jsonb(q) ORDER BY q.comissao DESC,q.mediador_id),'[]'::jsonb)
  FROM (SELECT p.mediador_id,count(*) AS partidas,sum(p.preco::bigint*j.quantidade) AS movimentado,
    sum(p.comissao*p.preco*j.quantidade) AS comissao FROM royal_partidas p
    CROSS JOIN LATERAL(SELECT count(*) AS quantidade FROM royal_partida_jogadores WHERE partida_id=p.id) j
    WHERE p.guild_id=p_guild_id AND p.status='finalizada' AND p.mediador_id IS NOT NULL AND p.finalizada_em>=p_desde_ms
    GROUP BY p.mediador_id) q
$$;

CREATE OR REPLACE FUNCTION public.royal_operacional_historico_apostas(p_guild_id text,p_user_id text,p_limite integer DEFAULT 10)
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$
  SELECT coalesce(jsonb_agg(to_jsonb(q)-'ordem' ORDER BY q.ordem DESC,q.id),'[]'::jsonb)
  FROM (
    SELECT p.id,p.modo,p.preco,p.gelo,p.status,p.vencedor_time,p.finalizada_em,p.motivo_fim,
      j.time AS meu_time,coalesce(p.finalizada_em,p.criado_em) AS ordem
    FROM royal_partidas p JOIN royal_partida_jogadores j ON j.partida_id=p.id
    WHERE p.guild_id=p_guild_id AND j.user_id=p_user_id AND p.status IN ('finalizada','cancelada')
    ORDER BY coalesce(p.finalizada_em,p.criado_em) DESC,p.id LIMIT greatest(1,p_limite)
  ) q
$$;

CREATE OR REPLACE FUNCTION public.royal_operacional_reservar_telagem(
  p_guild_id text,p_chave text,p_codigo text,p_links_ambiente text[] DEFAULT ARRAY[]::text[]
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_existente royal_telagens%rowtype; v_links text[]; v_url text; v_liberavel royal_telagens%rowtype;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended('royal-telagem:'||p_guild_id,0));
  SELECT * INTO v_existente FROM royal_telagens WHERE guild_id=p_guild_id AND chave=p_chave;
  IF FOUND THEN RETURN jsonb_build_object('chave',v_existente.chave,'url',v_existente.url,'codigo',v_existente.codigo,'origem','reservado'); END IF;
  SELECT array_agg(q.url ORDER BY q.prioridade,q.criado_em,q.url) INTO v_links FROM (
    SELECT url,min(prioridade) AS prioridade,min(criado_em) AS criado_em FROM (
      SELECT url,0 AS prioridade,ordem::bigint AS criado_em FROM unnest(coalesce(p_links_ambiente,ARRAY[]::text[])) WITH ORDINALITY e(url,ordem)
      UNION ALL SELECT url,1,criado_em FROM royal_telagem_links WHERE guild_id=p_guild_id
    ) fontes WHERE url ~* '^https://meet[.]google[.]com/[A-Za-z0-9_/?=&.\-]+$' GROUP BY url
  ) q;
  IF coalesce(array_length(v_links,1),0)=0 THEN RETURN NULL; END IF;
  SELECT l.url INTO v_url FROM unnest(v_links) WITH ORDINALITY l(url,ordem)
    WHERE NOT EXISTS(SELECT 1 FROM royal_telagens t WHERE t.guild_id=p_guild_id AND t.url=l.url) ORDER BY l.ordem LIMIT 1;
  IF v_url IS NULL THEN
    SELECT t.* INTO v_liberavel FROM royal_telagens t
    WHERE t.guild_id=p_guild_id AND t.url=ANY(v_links) AND NOT EXISTS(
      SELECT 1 FROM royal_partidas p WHERE p.guild_id=p_guild_id AND t.chave='partida:'||p.id
        AND p.status NOT IN ('finalizada','cancelada')
    ) ORDER BY t.criado_em,t.chave LIMIT 1;
    IF FOUND THEN
      DELETE FROM royal_telagens WHERE guild_id=p_guild_id AND chave=v_liberavel.chave;
      v_url:=v_liberavel.url;
    END IF;
  END IF;
  IF v_url IS NULL THEN RAISE EXCEPTION 'Todos os links do Google Meet do pool estão em uso. Peça a um ADM para adicionar mais com `/telagem_links adicionar`.'; END IF;
  INSERT INTO royal_telagens(guild_id,chave,codigo,url,criado_em) VALUES(p_guild_id,p_chave,p_codigo,v_url,royal_operacional_agora());
  RETURN jsonb_build_object('chave',p_chave,'url',v_url,'codigo',p_codigo,'origem','pool');
END $$;

CREATE OR REPLACE FUNCTION public.royal_operacional_fixar_telagem(p_guild_id text,p_chave text,p_url text,p_codigo text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
BEGIN
  IF p_url IS NULL OR p_url !~* '^https://meet[.]google[.]com/[A-Za-z0-9_/?=&.\-]+$' THEN RAISE EXCEPTION 'Link inválido. Use um link real do Meet.'; END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended('royal-telagem:'||p_guild_id,0));
  IF EXISTS(SELECT 1 FROM royal_telagens t WHERE t.guild_id=p_guild_id AND t.url=p_url AND t.chave<>p_chave
    AND EXISTS(SELECT 1 FROM royal_partidas p WHERE p.guild_id=p_guild_id AND t.chave='partida:'||p.id AND p.status NOT IN ('finalizada','cancelada'))) THEN
    RAISE EXCEPTION 'Esse link já está reservado para outra partida ativa.';
  END IF;
  DELETE FROM royal_telagens WHERE guild_id=p_guild_id AND url=p_url AND chave<>p_chave;
  INSERT INTO royal_telagens(guild_id,chave,codigo,url,criado_em) VALUES(p_guild_id,p_chave,p_codigo,p_url,royal_operacional_agora())
    ON CONFLICT(guild_id,chave) DO UPDATE SET codigo=excluded.codigo,url=excluded.url,criado_em=excluded.criado_em;
  RETURN jsonb_build_object('chave',p_chave,'url',p_url,'codigo',p_codigo,'origem','manual');
END $$;

CREATE OR REPLACE FUNCTION public.royal_operacional_limpar_telagem(p_guild_id text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_links integer; v_atribuicoes integer;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended('royal-telagem:'||p_guild_id,0));
  DELETE FROM royal_telagem_links WHERE guild_id=p_guild_id; GET DIAGNOSTICS v_links=ROW_COUNT;
  DELETE FROM royal_telagens WHERE guild_id=p_guild_id; GET DIAGNOSTICS v_atribuicoes=ROW_COUNT;
  RETURN jsonb_build_object('removidos',v_links,'atribuicoes',v_atribuicoes);
END $$;

-- Apenas importação explícita. Verifica novamente os saldos sob lock antes de
-- preencher campos zero, usa a RPC econômica existente e mantém extrato/replay.
CREATE OR REPLACE FUNCTION public.royal_operacional_importar_perfil(p_guild_id text,p_user_id text,p_dados jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_perfil royal_profiles%rowtype; v_deltas jsonb:='{}'::jsonb; v_campo text; v_local bigint; v_remoto bigint;
  v_request text:='legacy-migration:'||p_guild_id||':'||p_user_id;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended(trim(p_guild_id)||':'||v_request,0));
  IF EXISTS(SELECT 1 FROM royal_economy_requests WHERE guild_id=p_guild_id AND request_id=v_request) THEN
    RETURN jsonb_build_object('reconciliado',false,'jaImportado',true);
  END IF;
  INSERT INTO royal_profiles(guild_id,user_id) VALUES(p_guild_id,p_user_id) ON CONFLICT DO NOTHING;
  SELECT * INTO v_perfil FROM royal_profiles WHERE guild_id=p_guild_id AND user_id=p_user_id FOR UPDATE;
  FOREACH v_campo IN ARRAY ARRAY['coins','spins','wins','losses','wos','apostado','ganho'] LOOP
    v_local:=coalesce((p_dados->>v_campo)::bigint,0); v_remoto:=(to_jsonb(v_perfil)->>v_campo)::bigint;
    IF v_local<0 THEN RAISE EXCEPTION 'Valor legado negativo: %',v_campo; END IF;
    IF v_local<>0 AND v_remoto<>0 AND v_local<>v_remoto THEN RAISE EXCEPTION 'Conflito entre SQLite e Supabase no perfil %/% (%)',p_guild_id,p_user_id,v_campo; END IF;
    IF v_local<>0 AND v_remoto=0 THEN v_deltas:=v_deltas||jsonb_build_object(v_campo,v_local); END IF;
  END LOOP;
  IF v_deltas='{}'::jsonb THEN RETURN jsonb_build_object('reconciliado',false,'jaImportado',false); END IF;
  PERFORM * FROM royal_adjust_profile(p_guild_id,p_user_id,v_deltas,'importação inicial do SQLite',NULL,v_request);
  RETURN jsonb_build_object('reconciliado',true,'jaImportado',false);
END $$;

-- IDs legados são importados explicitamente. Avança identidades sem reduzir uma
-- sequência nem apagar registros; deve ser chamada ao terminar a importação.
CREATE OR REPLACE FUNCTION public.royal_operacional_reajustar_sequencias()
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_tabela text; v_seq text; v_max bigint; v_atual bigint;
BEGIN
  FOREACH v_tabela IN ARRAY ARRAY['royal_filas','royal_logs_dm','royal_transacoes'] LOOP
    v_seq:=pg_get_serial_sequence('public.'||v_tabela,'id');
    EXECUTE format('LOCK TABLE public.%I IN ACCESS EXCLUSIVE MODE',v_tabela);
    EXECUTE format('SELECT coalesce(max(id),0) FROM public.%I',v_tabela) INTO v_max;
    EXECUTE format('SELECT last_value FROM %s',v_seq::regclass) INTO v_atual;
    PERFORM setval(v_seq::regclass,greatest(v_max,v_atual,1),true);
  END LOOP;
END $$;

DO $$
DECLARE v_tabela text; v_funcao record; v_seq text;
BEGIN
  FOREACH v_tabela IN ARRAY ARRAY['royal_filas','royal_partidas','royal_partida_jogadores','royal_partida_go',
    'royal_blacklist','royal_paineis','royal_mensagens_painel','royal_plantao','royal_logs_dm',
    'royal_telagem_links','royal_telagens','royal_transacoes','royal_auditoria_legada'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',v_tabela);
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC,anon,authenticated',v_tabela);
    EXECUTE format('GRANT ALL ON TABLE public.%I TO service_role',v_tabela);
    v_seq:=NULL;
    IF v_tabela IN ('royal_filas','royal_logs_dm','royal_transacoes') THEN
      v_seq:=pg_get_serial_sequence('public.'||v_tabela,'id');
    END IF;
    IF v_seq IS NOT NULL THEN
      EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC,anon,authenticated',v_seq::regclass);
      EXECUTE format('GRANT ALL ON SEQUENCE %s TO service_role',v_seq::regclass);
    END IF;
  END LOOP;
  FOR v_funcao IN SELECT oid::regprocedure AS assinatura FROM pg_proc
    WHERE pronamespace='public'::regnamespace AND proname LIKE 'royal_operacional_%' LOOP
    EXECUTE format('REVOKE ALL ON FUNCTION %s FROM PUBLIC,anon,authenticated',v_funcao.assinatura);
    EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO service_role',v_funcao.assinatura);
  END LOOP;
END $$;
COMMIT;
