# O UPDATE direto deve esperar o advisory ANTES de obter row lock. Caso contrário,
# a RPC seguraria o advisory enquanto o UPDATE seguraria a linha: deadlock.
def start(name, sql):
    return subprocess.Popen(BASE + ['-c', sql], text=True, stdout=subprocess.PIPE,
                            stderr=subprocess.PIPE, env=dict(os.environ, PGAPPNAME=name))

def wait_event(name, event):
    deadline = time.monotonic() + 8
    while time.monotonic() < deadline:
        if run(f"SELECT count(*) FROM pg_stat_activity WHERE application_name='{name}' AND wait_event='{event}'") == '1':
            return
        time.sleep(.03)
    raise AssertionError(f'{name} não aguardou {event}')

