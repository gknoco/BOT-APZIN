def corrida_remocao(name, insert, remover, verifica):
    writer = holding(name + '_writer', insert)
    deleting = start(name + '_delete', remover)
    wait_event(name + '_delete', 'advisory')
    joined(writer)
    out, err = deleting.communicate(timeout=10)
    assert deleting.returncode == 0 and out.strip() == '1', (out, err)
    check(verifica, '0')

