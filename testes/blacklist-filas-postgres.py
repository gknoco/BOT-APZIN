def run(sql, *, ok=True, env=None):
    p = subprocess.run(BASE + ['-c', sql], text=True, capture_output=True, env=env, timeout=20)
    if ok and p.returncode:
        raise AssertionError(f'SQL falhou: {sql}\n{p.stderr}')
    if not ok and not p.returncode:
        raise AssertionError(f'SQL deveria falhar: {sql}\n{p.stdout}')
    return p.stdout.strip() if ok else p.stderr

def check(sql, expected):
    actual = run(sql)
    assert actual == expected, (sql, actual, expected)

def holding(name, sql):
    env = dict(os.environ, PGAPPNAME=name)
    child = subprocess.Popen(BASE + ['-c', f'BEGIN; {sql}; SELECT pg_sleep(2); COMMIT'],
                             text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE, env=env)
    deadline = time.monotonic() + 8
    while time.monotonic() < deadline:
        if child.poll() is not None:
            out, err = child.communicate()
            raise AssertionError(f'Transação terminou antes do marco de corrida: {out} {err}')
        if run(f"SELECT count(*) FROM pg_stat_activity WHERE application_name='{name}' AND wait_event='PgSleep'") == '1':
            return child
        time.sleep(.03)
    child.kill()
    raise AssertionError(f'Transação {name} não atingiu o marco de corrida')

def joined(child):
    out, err = child.communicate(timeout=10)
    assert child.returncode == 0, (out, err)

